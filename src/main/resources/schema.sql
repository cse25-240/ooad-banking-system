-- Banking System database schema (H2). Run automatically by DatabaseManager.createSchema().
-- One table per core class: customers, accounts, transactions, plus app_users for logins.
-- The CHECK and FOREIGN KEY rules repeat the key business rules inside the database as a second line of defence.

-- Customer (abstract) with IndividualCustomer and CompanyCustomer stored in one table.
-- customer_type says which subclass a row is, and the CHECK makes sure its own columns are filled in.
CREATE TABLE IF NOT EXISTS customers (
    customer_id     VARCHAR(20)  PRIMARY KEY,
    customer_type   VARCHAR(12)  NOT NULL,
    address         VARCHAR(200) NOT NULL,
    phone           VARCHAR(50)  NOT NULL,
    first_name      VARCHAR(60),
    surname         VARCHAR(60),
    national_id     VARCHAR(30)  UNIQUE,
    company_name    VARCHAR(120),
    registration_no VARCHAR(40)  UNIQUE,
    contact_person  VARCHAR(80),
    CONSTRAINT chk_customer_type CHECK (
        (customer_type = 'INDIVIDUAL' AND first_name IS NOT NULL AND surname IS NOT NULL AND national_id IS NOT NULL)
        OR
        (customer_type = 'COMPANY' AND company_name IS NOT NULL AND registration_no IS NOT NULL AND contact_person IS NOT NULL)
    )
);

-- Account (abstract) with Savings, Investment and Cheque in one table.
-- customer_id is NOT NULL and a FOREIGN KEY: an account cannot exist without a customer.
-- A customer holds at most one account of each type.
CREATE TABLE IF NOT EXISTS accounts (
    account_number     VARCHAR(20)   PRIMARY KEY,
    customer_id        VARCHAR(20)   NOT NULL,
    account_type       VARCHAR(12)   NOT NULL,
    branch_name             VARCHAR(60)   NOT NULL,
    opening_date          DATE          NOT NULL,
    balance            DECIMAL(15,2) NOT NULL,
    last_interest_paid VARCHAR(7),
    employer_name      VARCHAR(120),
    employer_address   VARCHAR(200),
    CONSTRAINT fk_account_customer FOREIGN KEY (customer_id) REFERENCES customers(customer_id),
    CONSTRAINT chk_account_type CHECK (account_type IN ('SAVINGS', 'INVESTMENT', 'CHEQUE')),
    CONSTRAINT chk_balance CHECK (balance >= 0),
    CONSTRAINT chk_investment_minimum CHECK (account_type <> 'INVESTMENT' OR balance >= 500),
    CONSTRAINT chk_cheque_employer CHECK (account_type <> 'CHEQUE' OR (employer_name IS NOT NULL AND employer_address IS NOT NULL)),
    CONSTRAINT uq_one_account_per_type UNIQUE (customer_id, account_type)
);

-- Transaction: a permanent record of every balance change.
-- seq keeps the exact order in which rows were written.
CREATE TABLE IF NOT EXISTS transactions (
    seq              BIGINT        GENERATED BY DEFAULT AS IDENTITY,
    transaction_id   VARCHAR(40)   PRIMARY KEY,
    account_number   VARCHAR(20)   NOT NULL,
    transaction_type VARCHAR(12)   NOT NULL,
    amount           DECIMAL(15,2) NOT NULL,
    balance_after    DECIMAL(15,2) NOT NULL,
    transaction_date TIMESTAMP     NOT NULL,
    description      VARCHAR(200),
    CONSTRAINT fk_transaction_account FOREIGN KEY (account_number) REFERENCES accounts(account_number) ON DELETE CASCADE,
    CONSTRAINT chk_transaction_type CHECK (transaction_type IN ('DEPOSIT', 'WITHDRAWAL', 'INTEREST')),
    CONSTRAINT chk_amount CHECK (amount > 0)
);

-- User: a login. Only a salted password hash is stored, never the password.
-- A CUSTOMER login points at exactly one customer, and staff logins have no customer.
CREATE TABLE IF NOT EXISTS app_users (
    user_id         VARCHAR(20)  PRIMARY KEY,
    username        VARCHAR(40)  NOT NULL UNIQUE,
    password_hash   VARCHAR(200) NOT NULL,
    role            VARCHAR(10)  NOT NULL,
    customer_id     VARCHAR(20),
    failed_attempts INT          NOT NULL DEFAULT 0,
    locked_until    TIMESTAMP,
    CONSTRAINT fk_user_customer FOREIGN KEY (customer_id) REFERENCES customers(customer_id),
    CONSTRAINT chk_role CHECK (role IN ('CUSTOMER', 'TELLER', 'ADMIN'))
);

CREATE INDEX IF NOT EXISTS idx_accounts_customer ON accounts(customer_id);
CREATE INDEX IF NOT EXISTS idx_transactions_account ON transactions(account_number);
